#!/usr/bin/env python3
"""Generate foundations/fonts.css from assets/fonts/*.woff2.

Fonts are embedded as base64 so every deliverable is self-contained.
Never link a web font service — it fails silently to a system sans (FID-12-14).
Stdlib only, so this runs anywhere with python3.
"""
import base64, pathlib, hashlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
FD = ROOT / "assets" / "fonts"
FACES = [
    ("ArchivoBlack.woff2",     "Archivo Black", 400, "normal"),
    ("Archivo-ExtraBold.woff2","Archivo",       800, "normal"),
    ("Archivo-Bold.woff2",     "Archivo",       700, "normal"),
    ("Archivo-SemiBold.woff2", "Archivo",       600, "normal"),
    ("Inter-Regular.woff2",    "Inter",         400, "normal"),
    ("Inter-Medium.woff2",     "Inter",         500, "normal"),
    ("Inter-SemiBold.woff2",   "Inter",         600, "normal"),
    ("Inter-Bold.woff2",       "Inter",         700, "normal"),
]
out = ["""/* =============================================================
   Nightlife Culture — embedded typefaces
   GENERATED by checks/build_fonts.py from assets/fonts/
   DO NOT EDIT BY HAND.
   Archivo and Inter, SIL Open Font License — embeddable.
   Base64 so any deliverable is self-contained. Never link a font
   service: it fails silently to a system sans (FID-12..14, Fixed).
   ============================================================= */"""]
missing = []
for fn, fam, wt, st in FACES:
    p = FD / fn
    if not p.exists():
        missing.append(fn); continue
    b64 = base64.b64encode(p.read_bytes()).decode()
    out.append(f"@font-face{{font-family:'{fam}';font-style:{st};font-weight:{wt};"
               f"font-display:swap;src:url(data:font/woff2;base64,{b64}) format('woff2')}}")
css = "\n".join(out) + "\n"
dest = ROOT / "foundations" / "fonts.css"
dest.write_text(css)
print(f"wrote {dest.relative_to(ROOT)}  {len(css):,} bytes  "
      f"{len(FACES)-len(missing)}/{len(FACES)} faces  sha {hashlib.sha256(css.encode()).hexdigest()[:16]}")
if missing:
    print("  MISSING (skipped):", ", ".join(missing))
