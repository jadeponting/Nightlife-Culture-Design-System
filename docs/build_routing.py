#!/usr/bin/env python3
"""Build the routing explainer, in two forms.

  docs/how-the-logic-works.html   LINKS ../foundations/*.css — always current
  dist/how-the-logic-works.html   embeds everything, for sending to someone

Prose lives in docs/routing.body.html — edit that, not this script.
The ladders, verdicts and finished components are GENERATED by running
components/route.py, so this page cannot claim behaviour the router does
not have. If the router changes, this page changes with it.

    python3 docs/build_routing.py

NC-SYS-06 — render the decision rather than describing it. This page is
generated from the system it describes, so it cannot claim behaviour the
system does not have.
"""
